/*
  Pastry silhouettes for the mascot: traces the subject outline in each white-pointed menu photo
  and writes src/generated/silhouettes.ts (polygons in % of the image frame).
  The mascot uses them to slip behind a pastry (clip-path hole in the pastry's exact shape)
  instead of fading out.
    node scripts/build-silhouettes.mjs
  Subject = saturated or dark pixels (the paper is #FFFFFF after white-pointing; soft grey
  shadows are excluded), largest connected blob, then a 72-ray radial outline from its centroid.
*/
import sharp from 'sharp';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const IDS = ['salt-bread', 'garlic-cc', 'cranberry-cc', 'twist-doughnut', 'croissant-sandwich']; // breads only (the latte is a drink)
const RAYS = 72;

async function trace(id) {
  const { data, info } = await sharp(path.join(root, `public/img/${id}-photo-600.webp`)).removeAlpha().raw().toBuffer({ resolveWithObject: true });
  const { width: w, height: h } = info;
  const on = new Uint8Array(w * h);
  for (let i = 0; i < w * h; i++) {
    const r = data[i * 3], g = data[i * 3 + 1], b = data[i * 3 + 2];
    const sat = Math.max(r, g, b) - Math.min(r, g, b);
    const lum = 0.299 * r + 0.587 * g + 0.114 * b;
    on[i] = sat > 46 || lum < 128 ? 1 : 0;
  }
  // close small gaps (dilate then erode, 2 px) so seeds, flour and cream stay inside the blob
  const morph = (src, keep) => {
    const out = new Uint8Array(w * h);
    for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
      let hit = keep ? 1 : 0;
      for (let dy = -2; dy <= 2 && hit === (keep ? 1 : 0); dy++) for (let dx = -2; dx <= 2; dx++) {
        const xx = x + dx, yy = y + dy;
        const v = xx < 0 || yy < 0 || xx >= w || yy >= h ? 0 : src[yy * w + xx];
        if (keep ? !v : v) { hit = keep ? 0 : 1; break; }
      }
      out[y * w + x] = hit;
    }
    return out;
  };
  const closed = morph(morph(on, false), true);
  // blobs (4-connected); keep every blob at least 15% the size of the largest (cranberry is two halves)
  const lab = new Int32Array(w * h).fill(-1);
  const sizes = [];
  const stack = [];
  for (let s = 0; s < w * h; s++) {
    if (!closed[s] || lab[s] !== -1) continue;
    const id2 = sizes.length; let n = 0;
    stack.push(s); lab[s] = id2;
    while (stack.length) {
      const p = stack.pop(); n++;
      const x = p % w, y = (p - x) / w;
      for (const q of [x > 0 ? p - 1 : -1, x < w - 1 ? p + 1 : -1, y > 0 ? p - w : -1, y < h - 1 ? p + w : -1]) {
        if (q >= 0 && closed[q] && lab[q] === -1) { lab[q] = id2; stack.push(q); }
      }
    }
    sizes.push(n);
  }
  const big = Math.max(...sizes);
  const keep = new Uint8Array(w * h);
  let sx = 0, sy = 0, sn = 0, minX = w, maxX = 0, minY = h, maxY = 0;
  for (let p = 0; p < w * h; p++) {
    if (lab[p] >= 0 && sizes[lab[p]] >= big * 0.15) {
      keep[p] = 1;
      const x = p % w, y = (p - x) / w;
      sx += x; sy += y; sn++;
      minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y);
    }
  }
  const cx = sx / sn, cy = sy / sn;
  const pts = [];
  for (let k = 0; k < RAYS; k++) {
    const a = (k / RAYS) * Math.PI * 2;
    const dx = Math.cos(a), dy = Math.sin(a);
    let far = 0;
    for (let t = 0; t < Math.hypot(w, h); t += 0.5) {
      const x = Math.round(cx + dx * t), y = Math.round(cy + dy * t);
      if (x < 0 || y < 0 || x >= w || y >= h) break;
      if (keep[y * w + x]) far = t;
    }
    pts.push([+((cx + dx * far) / w * 100).toFixed(1), +((cy + dy * far) / h * 100).toFixed(1)]);
  }
  return {
    center: [+(cx / w * 100).toFixed(1), +(cy / h * 100).toFixed(1)],
    box: [+(minX / w * 100).toFixed(1), +(minY / h * 100).toFixed(1), +(maxX / w * 100).toFixed(1), +(maxY / h * 100).toFixed(1)],
    outline: pts
  };
}

const out = {};
for (const id of IDS) { out[id] = await trace(id); console.log(id, out[id].box.join(' ')); }
const ts = `// Generated by scripts/build-silhouettes.mjs — do not edit by hand.
// Pastry outlines in % of the image frame (x, y), traced from the white-pointed photos.
export type Silhouette = { center: [number, number]; box: [number, number, number, number]; outline: [number, number][] };
export const silhouettes: Record<string, Silhouette> = ${JSON.stringify(out)};
`;
await fs.writeFile(path.join(root, 'src/generated/silhouettes.ts'), ts);
console.log('wrote src/generated/silhouettes.ts');
